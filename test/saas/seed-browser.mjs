import assert from "node:assert/strict";
import "reflect-metadata";
import { writeFile } from "node:fs/promises";
import pg from "pg";
import { signed, inquiry, modules } from "./fixtures.mjs";
assert.equal(process.env.SAAS_TEST_MODE, "true");
const url = new URL(process.env.SAAS_TEST_ADMIN_URL);
assert.equal(url.hostname, "127.0.0.1");
assert.match(url.pathname, /saas.*test/);
const pool = new pg.Pool({ connectionString: url.toString() }), m = modules(), tenants = new m.TenantsService();
const row = (await pool.query("SELECT * FROM saas_tenants WHERE slug='fixture-ake' AND chatwoot_account_id=10")).rows[0];
assert.ok(row);
const suffix = String(Date.now());
const body = inquiry({eventId:'browser-'+suffix,projectId:'browser-'+suffix,displayName:'Browser Buyer '+suffix,email:'browser-'+suffix+'@example.test',companyName:'Browser Company '+suffix});
const payload = signed(body, tenants.unseal(row.workspace_id,row.secrets).intakeSecret);
const response = await fetch('http://127.0.0.1:'+(process.env.SAAS_PREVIEW_PORT||14941)+'/api/v1/saas/intake/fixture-ake', {method:'POST',headers:payload.headers,body:payload.raw});
assert.ok(response.ok);
const data = await response.json();
await writeFile(process.argv[2],JSON.stringify({...data,label:body.displayName,company:body.companyName,project:'Browser Project '+suffix}),{mode:0o600});
await tenants.onModuleDestroy();await pool.end();
console.log('Fictional browser fixture ready');
